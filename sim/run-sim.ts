/**
 * Last Orbit — Monte Carlo balance simulator (v0.2 baseline).
 * Usage: npm run sim   → writes docs/balance/sim-report-v0.2.md
 * Deterministic: fixed seed base; no Date/Math.random.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  applyCommand, botCommand, createGame, matchReport, mulberry32Step, CARD_INFO,
} from '@last-orbit/game-core';
import type { BotPolicy, CardKind, Command, MatchReport } from '@last-orbit/game-core';

const GAMES_PER_CONFIG = 1500;
const SEED_BASE = 20261025;
const TURN_SECONDS_ESTIMATE = 20; // rough hotseat pace for projected real-time

interface Cfg { players: number; sunFury: boolean; derelicts: boolean; }

const CONFIGS: Cfg[] = [
  { players: 2, sunFury: false, derelicts: false },
  { players: 3, sunFury: false, derelicts: false },
  { players: 4, sunFury: false, derelicts: false },
  { players: 5, sunFury: false, derelicts: false },
  { players: 2, sunFury: true, derelicts: false },
  { players: 3, sunFury: true, derelicts: false },
  { players: 4, sunFury: true, derelicts: false },
  { players: 5, sunFury: true, derelicts: false },
  { players: 3, sunFury: true, derelicts: true },
  { players: 4, sunFury: true, derelicts: true },
  { players: 5, sunFury: true, derelicts: true },
];

function runOne(cfg: Cfg, policy: BotPolicy, seed: number): MatchReport | null {
  let s = createGame({
    playerCount: cfg.players,
    modules: { sunFury: cfg.sunFury, derelicts: cfg.derelicts },
    seed,
  });
  let st = ((seed * 2654435761) >>> 0) || 1;
  const rng = () => {
    const r = mulberry32Step(st);
    st = r.state;
    return r.value;
  };
  let guard = 0;
  while (s.phase !== 'game_over') {
    if (guard++ > 3000) return null; // deadlock guard (should never trigger)
    const cmd: Command | null = botCommand(s, policy, rng);
    if (!cmd) break;
    const res = applyCommand(s, cmd);
    if (!res.ok) throw new Error(`bot produced an illegal command: ${res.error}`);
    s = res.state;
  }
  return matchReport(s);
}

const mean = (xs: number[]): number => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const median = (xs: number[]): number => {
  if (!xs.length) return 0;
  const sorted = [...xs].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)];
};
const p90 = (xs: number[]): number => {
  if (!xs.length) return 0;
  const sorted = [...xs].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.ceil(sorted.length * 0.9) - 1)];
};
const r1 = (x: number): string => x.toFixed(1);
const pct = (x: number): string => `${(x * 100).toFixed(1)}%`;

interface Agg {
  reports: MatchReport[];
  turns: number[]; firstElim: number[]; downtime: number[]; maxDebt: number[];
  fury: number[]; comeback: number; passTurn: number[]; winnerSeats: number[];
  overridesPerGame: number[]; cancelledPerGame: number[]; stacks: number;
}

function aggregate(reports: MatchReport[], players: number): Agg {
  const a: Agg = {
    reports, turns: [], firstElim: [], downtime: [], maxDebt: [], fury: [],
    comeback: 0, passTurn: [], winnerSeats: Array(players).fill(0) as number[],
    overridesPerGame: [], cancelledPerGame: [], stacks: 0,
  };
  for (const rep of reports) {
    a.turns.push(rep.turns);
    if (rep.firstElimTurn !== null) a.firstElim.push(rep.firstElimTurn);
    a.downtime.push(...rep.downtimePerEliminated);
    a.maxDebt.push(rep.maxDebt);
    a.fury.push(rep.finalFury);
    if (rep.comeback) a.comeback += 1;
    a.passTurn.push(rep.passTurnRate);
    if (rep.winner !== null) a.winnerSeats[rep.winner] += 1;
    a.overridesPerGame.push(rep.overridesPlayed);
    a.cancelledPerGame.push(rep.cancelledActions);
    a.stacks = Math.max(a.stacks, rep.maxOverrideStack);
  }
  return a;
}

function configLabel(cfg: Cfg): string {
  const mods = [
    cfg.sunFury ? 'Sun Fury' : null,
    cfg.derelicts ? 'Derelicts' : null,
  ].filter(Boolean).join(' + ');
  return `${cfg.players}p${mods ? ` + ${mods}` : ' (vanilla)'}`;
}

function main(): void {
  const lines: string[] = [];
  const usage = new Map<CardKind, number>();
  let totalGames = 0;

  lines.push('# Balance Simulation Report — rules v0.2 (baseline)', '');
  lines.push(`Generated by \`npm run sim\` · ${CONFIGS.length} configs × ${GAMES_PER_CONFIG} games = ${(CONFIGS.length * GAMES_PER_CONFIG).toLocaleString('en-US')} matches · seed base ${SEED_BASE} · bots alternate random/greedy per game. Deterministic: identical seeds reproduce this report exactly.`, '');
  lines.push(`Projected real time ≈ turns × ${TURN_SECONDS_ESTIMATE}s per turn (hotseat pace, rough).`, '');

  lines.push('## Summary by configuration', '');
  lines.push('| Config | Games | Median turns | Mean turns | p90 turns | ≈Minutes (median) | 1st elimination (mean turn) | Downtime/elim (mean) | Contained | Fatal | Comebacks | Pass-turn rate | Winner hand |');
  lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|');

  const detailBlocks: string[] = [];
  for (let ci = 0; ci < CONFIGS.length; ci++) {
    const cfg = CONFIGS[ci];
    const reports: MatchReport[] = [];
    for (let g = 0; g < GAMES_PER_CONFIG; g++) {
      const policy: BotPolicy = g % 2 === 0 ? 'random' : 'greedy';
      const seed = SEED_BASE + ci * 1000003 + g * 7919;
      const rep = runOne(cfg, policy, seed);
      if (rep) reports.push(rep);
    }
    totalGames += reports.length;
    const a = aggregate(reports, cfg.players);
    const contained = reports.reduce((n, rep) => n + rep.rupturesContained, 0);
    const fatal = reports.reduce((n, rep) => n + rep.rupturesFatal, 0);
    for (const rep of reports) {
      for (const [k, v] of Object.entries(rep.playedCounts)) {
        usage.set(k as CardKind, (usage.get(k as CardKind) ?? 0) + (v ?? 0));
      }
    }
    const maxSeat = Math.max(...a.winnerSeats);
    lines.push(
      `| ${configLabel(cfg)} | ${reports.length} | ${median(a.turns)} | ${r1(mean(a.turns))} | ${p90(a.turns)} | ${r1((median(a.turns) * TURN_SECONDS_ESTIMATE) / 60)} | ${r1(mean(a.firstElim))} | ${r1(mean(a.downtime))} | ${contained} | ${fatal} | ${pct(a.comeback / reports.length)} | ${pct(mean(a.passTurn))} | ${r1(mean(reports.map((rep) => rep.winnerHandSize)))} |`,
    );

    detailBlocks.push(
      `**${configLabel(cfg)}**: mean flybys/game ${r1(mean(reports.map((x) => x.flybysPlayed)))} · mean max debt ${r1(mean(a.maxDebt))} (peak ${Math.max(...a.maxDebt)}) · overrides/game ${r1(mean(a.overridesPerGame))} · cancelled actions/game ${r1(mean(a.cancelledPerGame))} · tallest override stack ${a.stacks} · final Fury mean ${r1(mean(a.fury))} (Fury≥4 in ${pct(a.fury.filter((f) => f >= 4).length / a.fury.length)}) · transmissions used ${reports.reduce((n, x) => n + x.transmissionsUsed, 0)} · winner by seat ${a.winnerSeats.join('/')} (max seat share ${pct(maxSeat / reports.length)}) · rescans/reshuffles ${reports.reduce((n, x) => n + x.reshuffles, 0)}`,
    );
  }

  lines.push('', '## Detail', '');
  lines.push(...detailBlocks.map((b) => `- ${b}`));

  lines.push('', '## Card usage across all matches', '');
  lines.push('| Card | Plays per game (avg) |', '|---|---|');
  const kinds = [...usage.keys()].sort((x, y) => (usage.get(y) ?? 0) - (usage.get(x) ?? 0));
  for (const k of kinds) {
    lines.push(`| ${CARD_INFO[k].emoji} ${CARD_INFO[k].name} | ${r1((usage.get(k) ?? 0) / totalGames)} |`);
  }

  lines.push('', '## Reading notes', '');
  lines.push('- Winner-by-seat: gross imbalance shows as one seat >5pp above 1/N; all configs should be near-uniform.');
  lines.push('- Comeback rate: share of matches where the winner held the strictly smallest hand at some elimination.');
  lines.push('- Pass-turn rate: fraction of turns with zero card plays (high = boring "play nothing & pray" meta).');
  lines.push('- Downtime: turns an eliminated captain waited before the match ended (module target: Derelicts config should not inflate match length).');
  lines.push('', '---', '', '*This file is generated — do not hand-edit. Interpretation lives in `docs/10-balance-findings.md`.*');

  const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'balance', 'sim-report-v0.2.md');
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');
  console.log(`Simulated ${totalGames.toLocaleString('en-US')} games.`);
  console.log(`Report written: ${outPath}`);
}

main();

